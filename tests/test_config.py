"""The settings file: exclusions and governance additions, each with its reason, and nothing else."""
import json
import unittest

from agent_comment_lint import config


def parsed(*entries):
    return config.parse(json.dumps({"exclude": list(entries)}))


class TestParse(unittest.TestCase):
    def test_an_empty_object_excludes_nothing(self):
        self.assertEqual(config.parse("{}").exclusions, ())

    def test_an_exclusion_keeps_its_path_and_reason(self):
        loaded = parsed({"path": "public/worker.js", "reason": "generated by the mock library"})
        self.assertEqual(loaded.exclusions[0][:2], ("public/worker.js", "generated by the mock library"))

    def test_text_that_is_not_json_is_refused(self):
        with self.assertRaises(config.ConfigError):
            config.parse("{exclude: []}")

    def test_a_schema_line_is_accepted_and_ignored(self):
        loaded = config.parse('{"$schema": "https://example.com/s.json", "exclude": []}')
        self.assertEqual(loaded.exclusions, ())

    def test_a_schema_that_is_not_a_string_is_refused(self):
        with self.assertRaises(config.ConfigError):
            config.parse('{"$schema": 1}')

    def test_an_unknown_key_is_refused_so_no_rule_can_be_set_per_repository(self):
        for text in ('{"max_line": 200}', '{"exclude": [], "limits": {}}', "[]"):
            with self.assertRaises(config.ConfigError, msg=text):
                config.parse(text)

    def test_an_exclusion_without_a_reason_is_refused(self):
        for entry in ({"path": "a.js"}, {"path": "a.js", "reason": "  "}, {"path": "a.js", "reason": 1},
                      {"path": "a.js", "reason": "ok", "extra": 1}, "a.js"):
            with self.assertRaises(config.ConfigError, msg=repr(entry)):
                parsed(entry)

    def test_a_path_outside_the_root_is_refused(self):
        for path in ("/etc/x.js", "../x.js", "./x.js", ""):
            with self.assertRaises(config.ConfigError, msg=path):
                parsed({"path": path, "reason": "why"})


class TestGovernance(unittest.TestCase):
    def governance(self, value):
        return config.parse(json.dumps({"governance": value})).governance

    def test_no_governance_key_is_the_core_alone(self):
        self.assertIs(config.parse("{}").governance, config.EMPTY.governance)
        self.assertIsNone(config.EMPTY.governance.first_reference("see AB#4321"))

    def test_a_pack_and_an_extra_add_references(self):
        loaded = self.governance({"packs": ["azure-boards"],
                                  "extra": [{"pattern": "\\bWEB-\\d+", "reason": "the web team's tickets"}]})
        self.assertEqual(loaded.first_reference("see AB#4321"), "AB#4321")
        self.assertEqual(loaded.first_reference("see WEB-12"), "WEB-12")
        self.assertEqual(loaded.first_reference("see ADR-1"), "ADR-1")
        self.assertEqual(loaded.extras[0].reason, "the web team's tickets")

    def test_a_malformed_governance_setting_is_refused(self):
        for value in ([], {"packs": "azure-boards"}, {"packs": [1]}, {"packs": ["jira"]}, {"remove": ["ADR"]},
                      {"extra": {}}, {"extra": ["\\bWEB-\\d+"]}, {"extra": [{"pattern": "WEB-\\d+"}]},
                      {"extra": [{"pattern": "WEB-\\d+", "reason": " "}]},
                      {"extra": [{"pattern": "", "reason": "why"}]},
                      {"extra": [{"pattern": "WEB-(", "reason": "why"}]},
                      {"extra": [{"pattern": "x*", "reason": "why"}]},
                      {"extra": [{"pattern": "WEB-\\d+", "reason": "why", "flags": "i"}]}):
            with self.assertRaises(config.ConfigError, msg=repr(value)):
                self.governance(value)

    def test_the_agent_context_pack_parses(self):
        self.assertEqual(self.governance({"packs": ["agent-context"]}).packs, ("agent-context",))

    def test_an_unknown_pack_names_the_packs_there_are(self):
        with self.assertRaises(config.ConfigError) as caught:
            self.governance({"packs": ["jira"]})
        self.assertIn("azure-boards, decision-ids, task-ids", str(caught.exception))


class TestExcluded(unittest.TestCase):
    def excludes(self, pattern, path):
        return config.excluded(parsed({"path": pattern, "reason": "why"}), path)

    def test_a_plain_path_matches_only_itself(self):
        self.assertTrue(self.excludes("public/worker.js", "public/worker.js"))
        self.assertFalse(self.excludes("public/worker.js", "public/worker.js.map"))
        self.assertFalse(self.excludes("public/worker.js", "src/public/worker.js"))

    def test_a_trailing_slash_takes_the_whole_tree(self):
        self.assertTrue(self.excludes("docs/design/", "docs/design/a/b.js"))
        self.assertFalse(self.excludes("docs/design/", "docs/designs/a.js"))

    def test_a_single_star_stays_inside_one_directory(self):
        self.assertTrue(self.excludes("src/*.gen.ts", "src/api.gen.ts"))
        self.assertFalse(self.excludes("src/*.gen.ts", "src/deep/api.gen.ts"))

    def test_a_double_star_crosses_directories(self):
        self.assertTrue(self.excludes("**/*.gen.ts", "api.gen.ts"))
        self.assertTrue(self.excludes("**/*.gen.ts", "src/deep/api.gen.ts"))
        self.assertTrue(self.excludes("vendor/**", "vendor/a/b.css"))
        self.assertFalse(self.excludes("vendor/**", "src/vendor/a.css"))

    def test_a_dot_in_a_pattern_is_a_literal_dot(self):
        self.assertFalse(self.excludes("a.js", "abjs"))

    def test_no_settings_exclude_nothing(self):
        self.assertFalse(config.excluded(config.EMPTY, "src/a.ts"))


class TestDefaultSkips(unittest.TestCase):
    def test_dependency_and_build_directories_are_skipped_at_any_depth(self):
        for path in ("node_modules/a/index.js", "src/app/bin/Debug/a.cs", "web/dist/a.js", ".venv/lib/a.py",
                     "src/Data/Migrations/Init.cs", ".claude/hooks/guard.py"):
            self.assertTrue(config.skipped_by_default(path), path)

    def test_a_file_that_only_shares_a_skipped_name_is_judged(self):
        self.assertFalse(config.skipped_by_default("src/build.ts"))
        self.assertFalse(config.skipped_by_default("src/binary/a.cs"))
        self.assertFalse(config.skipped_by_default("tools/build"))
